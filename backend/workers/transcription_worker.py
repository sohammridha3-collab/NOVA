#!/usr/bin/env python3
"""
NOVA Backend — Standalone Faster-Whisper Transcription Worker
Stage 3 Voice Pipeline Component

Features:
- Powered by faster-whisper (CTranslate2 optimized Whisper)
- Multilingual support: English (en), Bengali (bn), Hindi (hi), or Auto-detect (auto/None)
- Voice Activity Detection (VAD) via Silero VAD filter
- Silence & low-confidence artifact suppression (never returns junk for silence)
- Standard JSON output contract to stdout
"""

import sys
import os
import json
import argparse
import math

try:
    from faster_whisper import WhisperModel
except ImportError:
    print(json.dumps({
        "success": False,
        "error": "faster-whisper package not installed. Run 'pip install faster-whisper'.",
        "code": "FASTER_WHISPER_NOT_INSTALLED"
    }))
    sys.exit(1)


def parse_args():
    parser = argparse.ArgumentParser(description="NOVA Faster-Whisper Transcription Worker")
    parser.add_argument("--input", required=True, help="Path to input audio file")
    parser.add_argument("--language", default="auto", choices=["auto", "en", "bn", "hi"],
                        help="Language: en (English), bn (Bengali), hi (Hindi), or auto")
    parser.add_argument("--model", default=os.environ.get("WHISPER_MODEL", "tiny"),
                        help="Model size: tiny, base, small, medium, large-v3 (default: tiny)")
    parser.add_argument("--device", default=os.environ.get("WHISPER_DEVICE", "cpu"),
                        help="Device to run on: cpu, cuda")
    parser.add_argument("--compute_type", default=os.environ.get("WHISPER_COMPUTE_TYPE", "int8"),
                        help="Compute type: int8, float16, float32")
    parser.add_argument("--vad", action="store_true", default=True,
                        help="Enable voice activity detection filter")
    return parser.parse_args()


def transcribe_audio(audio_path, language="auto", model_name="tiny", device="cpu", compute_type="int8", use_vad=True):
    if not os.path.exists(audio_path):
        return {
            "success": False,
            "error": f"Audio file not found: {audio_path}",
            "code": "FILE_NOT_FOUND"
        }

    try:
        # Load model (uses local huggingface cache)
        model = WhisperModel(model_name, device=device, compute_type=compute_type)

        lang_param = None if language == "auto" or not language else language

        vad_params = dict(
            min_silence_duration_ms=400,
            threshold=0.45
        ) if use_vad else None

        segments_gen, info = model.transcribe(
            audio_path,
            language=lang_param,
            vad_filter=use_vad,
            vad_parameters=vad_params,
            beam_size=5,
            best_of=5,
            temperature=0.0
        )

        segments = []
        full_text_parts = []
        total_logprob = 0.0
        total_tokens = 0

        for seg in segments_gen:
            clean_text = seg.text.strip()
            if clean_text:
                full_text_parts.append(clean_text)
                segments.append({
                    "start": round(seg.start, 2),
                    "end": round(seg.end, 2),
                    "text": clean_text,
                    "avg_logprob": round(seg.avg_logprob, 3),
                    "no_speech_prob": round(seg.no_speech_prob, 3)
                })
                total_logprob += seg.avg_logprob
                total_tokens += 1

        full_text = " ".join(full_text_parts).strip()
        duration = round(info.duration, 2) if hasattr(info, "duration") else 0.0
        detected_lang = info.language if hasattr(info, "language") else (language if language != "auto" else "unknown")
        lang_prob = round(info.language_probability, 3) if hasattr(info, "language_probability") else 1.0

        # Silence / Hallucination Detection:
        # 1. No segments generated by VAD
        # 2. Text is empty or consists purely of whitespace/punctuation
        # 3. All segments have high no_speech_prob (> 0.75)
        is_silent = False
        if not full_text:
            is_silent = True
        elif segments and all(s.get("no_speech_prob", 0) > 0.75 for s in segments):
            is_silent = True
            full_text = ""

        # Calculate approximate confidence score (0.0 to 1.0)
        confidence = 0.0
        if not is_silent and total_tokens > 0:
            avg_lp = total_logprob / total_tokens
            confidence = round(max(0.0, min(1.0, math.exp(avg_lp))), 3)

        return {
            "success": True,
            "text": full_text,
            "is_silent": is_silent,
            "language": detected_lang,
            "language_probability": lang_prob,
            "duration": duration,
            "confidence": confidence,
            "segments_count": len(segments),
            "segments": segments
        }

    except Exception as exc:
        return {
            "success": False,
            "error": str(exc),
            "code": "TRANSCRIPTION_ERROR"
        }


def main():
    args = parse_args()
    result = transcribe_audio(
        audio_path=args.input,
        language=args.language,
        model_name=args.model,
        device=args.device,
        compute_type=args.compute_type,
        use_vad=args.vad
    )
    print(json.dumps(result))
    if not result.get("success"):
        sys.exit(1)


if __name__ == "__main__":
    main()

